# Ejercicio 2: Área de un triángulo
# Instrucciones:
# - Pedir al usuario la base del triángulo.
# - Pedir la altura del triángulo.
# - Calcular el área usando la fórmula: (base * altura) / 2.
# - Mostrar el resultado con el mensaje: "El área del triángulo es: ".

# Tu código aquí:

# Pedir la base:
base = float(input("ingresar la base del triangulo"))

# Pedir la altura:
altura = float(input("ingresar la altura del triangulo"))

# Calcular el área:
área = (base * altura) / 2

# Mostrar el resultado:
# print("El área del triángulo es:", ...)
print ("el área del triangulo es:", área)